use super::*;

const TX: TxId = *b"0123456789ab";

#[test]
fn o_pedido_tem_o_cabecalho_do_rfc() {
    let r = request(&TX);
    assert_eq!(&r[..4], &[0, 1, 0, 0]);
    assert_eq!(&r[4..8], &[0x21, 0x12, 0xA4, 0x42]);
    assert_eq!(&r[8..], &TX);
}

#[test]
fn a_resposta_devolve_o_endereco_visto_em_ipv4_e_ipv6() {
    for seen in ["203.0.113.5:47321", "[2001:db8::1:2]:5"] {
        let seen: SocketAddr = seen.parse().unwrap();
        assert_eq!(response(&answer(&TX, seen)), Some((TX, seen)), "{seen}");
    }
}

/// O vector de teste oficial (RFC 5769 §2.2): resposta IPv4, mapeado 192.0.2.1:32853, com SOFTWARE
/// antes e MESSAGE-INTEGRITY e FINGERPRINT depois do XOR-MAPPED-ADDRESS (atributos que ignoramos).
#[test]
fn o_vector_do_rfc_5769() {
    let tx: TxId = [
        0xb7, 0xe7, 0xa7, 0x01, 0xbc, 0x34, 0xd6, 0x86, 0xfa, 0x87, 0xdf, 0xae,
    ];
    let msg: [u8; 80] = [
        0x01, 0x01, 0x00, 0x3c, 0x21, 0x12, 0xa4, 0x42, 0xb7, 0xe7, 0xa7, 0x01, 0xbc, 0x34, 0xd6,
        0x86, 0xfa, 0x87, 0xdf, 0xae, 0x80, 0x22, 0x00, 0x0b, 0x74, 0x65, 0x73, 0x74, 0x20, 0x76,
        0x65, 0x63, 0x74, 0x6f, 0x72, 0x20, 0x00, 0x20, 0x00, 0x08, 0x00, 0x01, 0xa1, 0x47, 0xe1,
        0x12, 0xa6, 0x43, 0x00, 0x08, 0x00, 0x14, 0x2b, 0x91, 0xf5, 0x99, 0xfd, 0x9e, 0x90, 0xc3,
        0x8c, 0x74, 0x89, 0xf9, 0x2a, 0xf9, 0xba, 0x53, 0xf0, 0x6b, 0xe7, 0xd7, 0x80, 0x28, 0x00,
        0x04, 0xc0, 0x7d, 0x4c, 0x96,
    ];
    assert_eq!(
        response(&msg),
        Some((tx, "192.0.2.1:32853".parse().unwrap()))
    );
}

#[test]
fn lixo_e_outros_tipos_nao_sao_resposta() {
    assert_eq!(response(&request(&TX)), None, "um pedido não é resposta");
    assert_eq!(response(&[0u8; 19]), None);
    let mut a = answer(&TX, "1.2.3.4:5".parse().unwrap());
    a.truncate(a.len() - 3);
    assert_eq!(response(&a), None, "atributo cortado");
}
