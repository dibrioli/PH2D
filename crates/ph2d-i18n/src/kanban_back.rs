/// As listas numeradas: meses (`mon.1`, `month.1`), dias da semana a partir de segunda (`wd.0`) e
/// os lembretes pela ordem do seletor (`remind.0`).
fn numbered(rest: &str) -> Option<&'static str> {
    const MON: [&str; 12] = [
        "Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec",
    ];
    const MONTH: [&str; 12] = [
        "January",
        "February",
        "March",
        "April",
        "May",
        "June",
        "July",
        "August",
        "September",
        "October",
        "November",
        "December",
    ];
    const WD: [&str; 7] = ["Mo", "Tu", "We", "Th", "Fr", "Sa", "Su"];
    const REMIND: [&str; 9] = [
        "None",
        "At time of due date",
        "5 Minutes before",
        "10 Minutes before",
        "15 Minutes before",
        "1 Hour before",
        "2 Hours before",
        "1 Day before",
        "2 Days before",
    ];
    let (list, n) = rest.split_once('.')?;
    let n: usize = n.parse().ok()?;
    match list {
        "mon" => MON.get(n.checked_sub(1)?).copied(),
        "month" => MONTH.get(n.checked_sub(1)?).copied(),
        "wd" => WD.get(n).copied(),
        "remind" => REMIND.get(n).copied(),
        _ => None,
    }
}
