//! The knob REGISTRY TABLE (SPEC §16 defaults + §17 gated extensions) — the
//! data half of [`super`]: every row is a [`KnobDef`] in [`Knob`] discriminant
//! order (the parent's gate pins table order == enum order). The typed surface
//! (the [`Knob`] enum, groups, the live [`super::Tuning`] values) stays in the
//! parent; this file is the one place a default/range/step lives.

use super::{KNOB_COUNT, Knob, KnobGroup, Rebuild};

pub struct KnobDef {
    pub knob: Knob,
    pub group: KnobGroup,
    pub key: &'static str,
    pub min: f64,
    pub max: f64,
    pub step: f64,
    pub default: f64,
    pub rebuild: Option<Rebuild>,
}

const fn k(
    knob: Knob,
    group: KnobGroup,
    key: &'static str,
    min: f64,
    max: f64,
    step: f64,
    default: f64,
    rebuild: Option<Rebuild>,
) -> KnobDef {
    KnobDef {
        knob,
        group,
        key,
        min,
        max,
        step,
        default,
        rebuild,
    }
}

