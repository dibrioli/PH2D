/// O código Unicode do byte `b` numa fonte do conjunto `charset` (sem tabela: o próprio byte).
pub fn charset_to_unicode(charset: u8, b: u8) -> u32 {
    let table: &[u32] = match charset {
        0 => &CP1252,
        1 => &CP1252,
        77 => &MAC_ROMAN,
        161 => &CP1253,
        162 => &CP1254,
        163 => &CP1258,
        177 => &CP1255,
        178 => &CP1256,
        186 => &CP1257,
        204 => &CP1251,
        222 => &CP874,
        238 => &CP1250,
        255 => &CP437,
        _ => return u32::from(b),
    };
    if table.len() == 256 {
        table[usize::from(b)]
    } else if b < 0x80 {
        u32::from(b)
    } else {
        table[usize::from(b - 0x80)]
    }
}
