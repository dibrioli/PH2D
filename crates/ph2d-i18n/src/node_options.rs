/// Resolve uma chave de opcao; `None` deixa o chamador seguir para a proxima tabela.
#[must_use]
pub(crate) fn tr(chave: &str) -> Option<&'static str> {
    ENTRADAS
        .binary_search_by_key(&chave, |(k, _)| k)
        .ok()
        .map(|i| ENTRADAS[i].1)
}

