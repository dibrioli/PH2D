//! As OPCOES de cada selector de nó — `node.<tipo>.param.<param>.<i>` e
//! `node.opts.<crate>.<CONST>.<i>`.
//!
//! A 5.a fatia da fronteira dos motores, e a irma das
//! [`super::node_params`]/[`super::node_params_motion`], que guardam o ROTULO da pergunta;
//! esta guarda as RESPOSTAS.
//!
//! ⚠️⚠️ **A chave deriva do sitio de DECLARACAO do array, e sao dois sitios porque sao duas
//! identidades.** Um array escrito INLINE dentro de um `ParamUiHint` pertence a um par
//! `(tipo, param)` e a mais ninguem; uma `const` e' um VOCABULARIO com N leitores — o
//! `ph2d_motion_region::SHAPE_LABELS` e' lido por quatro nos e o `ph2d_nodegraph::pivot::LABELS`
//! por tres. ⛔ Uma chave derivada do NO daria N copias do mesmo texto, e mudar uma nao mudava
//! as outras.
//!
//! ⛔ **E o NOME da const nao e' a identidade dela:** `MODE_LABELS` existe em SEIS crates de no
//! com conteudos diferentes (`2 · 2 · 3 · 2 · 6 · 2` opcoes). Uma regra que lesse o nome daria a
//! mesma chave a seis vocabularios distintos ⇒ a resolucao e' feita dentro da crate do USO, e so'
//! um caminho qualificado (`ph2d_motion_region::`, `ph2d_nodegraph::`) sai dela.
//!
//! ⚠️⚠️ **E aqui quem traduz e' o PINTOR, nao a fronteira — ao contrario do rotulo, e o motivo
//! e' o TIPO.** O `label` de uma row e' um `&'static str` e pode ser trocado por outro; as
//! opcoes sao um `&'static [&'static str]` **dentro de um `ParamUiHint` que e' `Copy`** e vive
//! em 800 sitios de struct-literal — reconstrui-lo na fronteira obrigava a alocar por quadro no
//! caminho de OMISSAO (o cartao). ⇒ o array carrega as chaves ate' ao pintor, que resolve so' as
//! opcoes que de facto desenha. O gate e' o `no_enum_option_of_any_node_paints_a_raw_key`.
//!
//! ⚠️ **E os CANAIS de um `ParamWidget::Channels` entram aqui pela mesma lei** — um picker de
//! canal e' um selector, e as entradas dele sao as opcoes que o artista escolhe. ⛔ A chave deles
//! **nao** pode ser a coluna sozinha: `P` serve quatro canais (`Position X`, `Position Y`,
//! `Radius`, `Angle`) e a identidade e' o par `(coluna, modo)`, que e' exactamente o que o
//! produto usa para os achar (`c.column == *col && c.mode == *modo`). ⇒
//! `node.channel.<coluna>.<modo>`, com o modo pelo NOME da constante que o declara e nunca pelo
//! numero dela — um `MODE_COMPONENT_BASE` que mudasse de valor renomearia as chaves todas.

