//! `ErasedPanel` — type-erased wrapper around `Panel<State>`.
//!
//! ADR-0029 §4.4. The registry guards `Vec<ErasedPanel>` (not
//! `&'static PanelManifest`). At install time, `ErasedPanel::new::<P>()`
//! creates a default `P::State` boxed; subsequent calls downcast
//! that box once per dispatch.
//!
//! The downcast is technically `dyn Any::downcast_mut` which panics
//! on type mismatch. By construction this never happens: the
//! manifest stores fn pointers that hard-code the `<P>` type-param,
//! and the state was created via the same `P` at install. A
//! mismatch would mean a corrupted manifest, which the type system
//! prevents.

use super::EventOutcome;
use super::PaintCtx;
use super::Panel;
use super::PanelHostInternal;
use super::PanelManifest;
use crate::interaction::{WidgetEvent, WidgetStore};
use std::any::Any;
use std::thread::ThreadId;

/// O estado de um painel num fio: o da pintura na app, o de cada teste no libtest.
struct DoFio {
    fio: ThreadId,
    state: Box<dyn Any + Send>,
    /// ⭐⭐⭐ **A coluna do valor deste painel** — os pedidos de coluna que as secções dele já
    /// fizeram (ordem do dono, 2026-09-23: *«quero tudo alinhado e padronizado»*). Ver
    /// [`crate::widget::ColunaDoPainel`]. ⚠️ Mora AQUI porque este é o único sítio por onde toda
    /// pintura de painel passa — e é por painel, porque famílias diferentes têm nomes diferentes.
    coluna: crate::widget::ColunaDoPainel,
}

/// One entry in the runtime panel registry. Holds the manifest
/// (fn pointers + identity) plus the panel's owned state as a
/// `Box<dyn Any>`. Methods downcast to the typed `P::State` via
/// the manifest's `state_type_check`.
///
/// ⭐ O estado é **por fio**, como os `thread_local` que o painel lê ao lado dele (o que a shell publica):
/// metade por processo e metade por fio fazia dois testes em paralelo trocarem o `last_entity` do Inspector
/// um ao outro, e a troca larga o arrasto (medido 04/11, `docs/DevOps/FLAKES_DE_CARGA.md`). A app pinta num
/// fio só: tem uma entrada. O libtest passa a ver o que o nextest vê, um estado por teste.
pub struct ErasedPanel {
    pub manifest: PanelManifest,
    novo_estado: fn() -> Box<dyn Any + Send>,
    fios: Vec<DoFio>,
}

impl ErasedPanel {
    pub fn new<P: Panel>() -> Self {
        Self {
            manifest: PanelManifest::for_panel::<P>(),
            novo_estado: || Box::new(<P::State>::default()),
            fios: Vec::new(),
        }
    }

    fn do_fio(&mut self) -> &mut DoFio {
        let fio = std::thread::current().id();
        let i = if let Some(i) = self.fios.iter().position(|f| f.fio == fio) {
            i
        } else {
            self.fios.push(DoFio {
                fio,
                state: (self.novo_estado)(),
                coluna: crate::widget::ColunaDoPainel::default(),
            });
            self.fios.len() - 1
        };
        &mut self.fios[i]
    }

    /// Dispatch the panel's paint via its manifest. The manifest's
    /// `paint_fn` receives `&mut dyn Any` and does the typed
    /// downcast internally (the fn is generated by `PanelManifest::
    /// for_panel::<P>` and knows the exact `P::State` type).
    pub fn paint(&mut self, ctx: &mut PaintCtx) {
        let paint_fn = self.manifest.paint_fn;
        let DoFio { state, coluna, .. } = self.do_fio();
        coluna.pintando(|| paint_fn(state.as_mut(), ctx));
    }

    /// Dispatch the panel's apply_event via its manifest.
    pub fn apply_event(
        &mut self,
        host: &mut dyn PanelHostInternal,
        ev: WidgetEvent,
    ) -> EventOutcome {
        let apply_event_fn = self.manifest.apply_event_fn;
        apply_event_fn(self.do_fio().state.as_mut(), host, ev)
    }

    /// Pre-register widget `NodeId`s. No state involved.
    pub fn populate(&self, store: &mut WidgetStore) {
        (self.manifest.populate_fn)(store);
    }
}
