//! **OS NOMES DOS NÓS** — a 3.ª fatia da fronteira dos motores.
//!
//! ⛔⛔ **O mesmo defeito, pela terceira vez:** o `ph2d-panel-motion-graph` pinta o nome de cada
//! cartão e o `ph2d-app-motion` pinta a paleta, e as duas crates têm censo — enquanto os
//! literais vivem nos **135 crates `ph2d-node-*`**, que não têm nenhum.
//!
//! # ⭐ A chave deriva do TIPO do nó, e o tipo deriva do nome da CRATE
//!
//! `ph2d-node-motion-wiggle` → tokens `motion`,`wiggle` → o manifesto cujo nome, partido em `.` e
//! `_`, dá os mesmos tokens: `motion.wiggle`. ⇒ `node.motion.wiggle.name`.
//!
//! ⚠️ **A regra resolve `130` de `133` e as três excepções estão NOMEADAS**, porque uma regra com
//! excepções escritas é uma lei e uma regra com excepções caladas é um palpite: o
//! `ph2d-node-motion-shape` declara `source.shape` (o tipo foi renomeado e a crate manteve o nome
//! antigo), o `ph2d-node-util-reroute` não tem manifesto de UI, e a `ph2d-node-registry` **não é um
//! nó** — os manifestos dela são fixturas de teste.
//!
//! ⚠️ **O nome do nó NÃO é derivável do tipo:** `motion.four_point_warp` mostra-se *Corner Pin* e
//! `source.lsystem` mostra-se *L-System*. A chave é; o texto vive aqui.

