/// Resolve uma chave de opcao da familia `value`; `None` deixa o chamador seguir.
#[must_use]
pub(crate) fn tr(chave: &str) -> Option<&'static str> {
    ENTRADAS
        .binary_search_by_key(&chave, |(k, _)| k)
        .ok()
        .map(|i| ENTRADAS[i].1)
}

#[cfg(test)]
mod tests {
    /// A busca binaria exige a tabela ORDENADA e sem repetidos.
    #[test]
    fn the_value_options_are_sorted_and_unique() {
        for w in super::ENTRADAS.windows(2) {
            assert!(w[0].0 < w[1].0, "fora de ordem: {} >= {}", w[0].0, w[1].0);
        }
    }
}
