//! O que o BUTLER do Kanban diz (TrelloClone W8/J2): as palavras das frases das automações
//! (`kanban.auto.<Palavra>`, uma por `ph2d_kanban_auto::Word` — o gate da família percorre
//! `Word::ALL`) e o painel de automação (`kanban.auto.ui.*`). O idioma do Butler: «when a card is
//! moved into Done, mark the due date complete and archive the card».

/// A tradução de uma chave do Butler, ou `None` se ela não é daqui.
pub(crate) fn tr(key: &str) -> Option<&'static str> {
    let rest = key.strip_prefix("kanban.auto.")?;
    if let Some(ui) = rest.strip_prefix("ui.") {
        return ui_text(ui);
    }
    word(rest)
}

